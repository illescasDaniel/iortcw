/*
================
BG_CodApplyOptions

codmod: the player-facing toggles (cod_opt*) switch whole groups of mechanics back to vanilla by clearing the
feature flags and tunables that group owns, after every cvar refresh. Server and cgame run the same code on the
same archived cvars, so prediction stays in step. Group -> flags: docs/gameplay-options.md.
================
*/
static void BG_CodApplyOptions( void ) {
	if ( !bg_cod.optMovement ) {
		bg_cod.moveEnable = 0;
		bg_cod.leanEnable = 0;
		bg_cod.landSlowEnable = 0;
		bg_cod.gaitEnable = 0;
		bg_cod.duckTime = 100;      // vanilla-equivalent smoothing (table defaults)
		bg_cod.duckEase = 0;
		bg_cod.duckGunDip = 0;
	}
	// sliding starts from the CoD sprint flag, which only exists with the CoD movement
	if ( !bg_cod.optSlide || !bg_cod.optMovement ) {
		bg_cod.slideEnable = 0;
	}
	if ( !bg_cod.optProne ) {
		bg_cod.proneEnable = 0;
	}
	if ( !bg_cod.optAiming ) {
		bg_cod.adsEnable = 0;
		bg_cod.adsSwayEnable = 0;
		bg_cod.crosshairStyle = 0;
	}
	if ( !bg_cod.optRecoil ) {
		bg_cod.recoilEnable = 0;
	}
	if ( !bg_cod.optWeapon ) {
		bg_cod.weaponEnable = 0;
		bg_cod.quickKnifeEnable = 0;
		bg_cod.kickDamage = 15;
	}
	if ( !bg_cod.optRegen ) {
		bg_cod.healthRegenEnable = 0;
		bg_cod.maxHealth = 0;
	}
	bg_cod.staminaEnable = bg_cod.optStamina;
	if ( !bg_cod.optAmmo ) {
		bg_cod.ammoScale = 1;
	}
	if ( !bg_cod.optHitMarkers ) {
		bg_cod.hitMarkerEnable = 0;
	}
	if ( !bg_cod.optEnemy ) {
		bg_cod.aiSpeedMode = 0;
		bg_cod.aiSprint = 0;
	}
	if ( !bg_cod.optTactics ) {
		bg_cod.aiTactics = 0;
	}
}

/*
================
BG_CodRegisterCvars

codmod: registers every entry of bg_codCvars into the caller's vmCvar_t array (one slot
per entry, in order), then applies the just-registered values into bg_cod.
================
*/
void BG_CodRegisterCvars( vmCvar_t *cvars, int maxCvars ) {
	int i;
	int n;

	n = bg_numCodCvars;
	if ( n > maxCvars ) {
		n = maxCvars;    // codmod: should never happen -- bump BG_COD_MAX_CVARS if it does
	}

	for ( i = 0; i < n; i++ ) {
		trap_Cvar_Register( &cvars[i], bg_codCvars[i].name, bg_codCvars[i].def, bg_codCvars[i].flags );
	}

	BG_CodUpdateCvars( cvars, n );
}

/*
================
BG_CodUpdateCvars

codmod: pulls current cvar values into bg_cod. Called every frame from G_UpdateCvars /
CG_UpdateCvars so cvar changes (and savegame loads, see architecture.md section 7) take
effect immediately.
================
*/
void BG_CodUpdateCvars( vmCvar_t *cvars, int maxCvars ) {
	int i;
	int n;
	byte *dst;

	n = bg_numCodCvars;
	if ( n > maxCvars ) {
		n = maxCvars;
	}

	for ( i = 0; i < n; i++ ) {
		trap_Cvar_Update( &cvars[i] );

		dst = (byte *)&bg_cod + bg_codCvars[i].ofs;
		if ( bg_codCvars[i].isInt ) {
			*(int *)dst = cvars[i].integer;
		} else {
			*(float *)dst = cvars[i].value;
		}
	}

	BG_CodApplyOptions();
}

