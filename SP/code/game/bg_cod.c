/*
================
BG_CodFireSpreadScale

codmod: CoD hip → ADS cone. Hip uses max(aimSpread, hipSpreadMin) * hipSpreadScale;
ADS lerps that toward aimSpread * adsSpreadScale. adsFrac 0 = full hip, 1 = full ADS.
================
*/
float BG_CodFireSpreadScale( float aimSpread, int weapon, float adsFrac ) {
	float hip;
	float ads;
	float hipMin = bg_cod.hipSpreadMin;
	float hipMul = bg_cod.hipSpreadScale;

	if ( aimSpread < 0.0f ) {
		aimSpread = 0.0f;
	} else if ( aimSpread > 1.0f ) {
		aimSpread = 1.0f;
	}
	if ( adsFrac < 0.0f ) {
		adsFrac = 0.0f;
	} else if ( adsFrac > 1.0f ) {
		adsFrac = 1.0f;
	}

	hip = aimSpread;
	if ( hipMin > 0.0f && hip < hipMin ) {
		hip = hipMin;
	}
	if ( hipMul > 0.0f && hipMul != 1.0f ) {
		hip *= hipMul;
	}
	if ( hip > 1.0f ) {
		hip = 1.0f;
	}

	ads = aimSpread * BG_CodAdsSpreadScale( weapon );

	if ( adsFrac <= 0.0f ) {
		return hip;
	}
	if ( adsFrac >= 1.0f ) {
		return ads;
	}
	return hip + ( ads - hip ) * adsFrac;
}

/*
================
BG_CodMaxAmmo

codmod: scaled max reserve for the player when cod_ammoScale > 1 (phase 5b).
Does not mutate ammoTable (shared with AI).
================
*/
int BG_CodMaxAmmo( int weapon ) {
	int maxa;

	if ( weapon < 0 || weapon >= WP_NUM_WEAPONS ) {
		return 0;
	}
	maxa = ammoTable[weapon].maxammo;
	if ( bg_cod.enable && bg_cod.vitalsEnable && bg_cod.ammoScale > 1.0f ) {
		maxa = (int)( maxa * bg_cod.ammoScale + 0.5f );
	}
	return maxa;
}

/*
================
BG_CodCanADS

codmod: ADS eligibility from playerState_t alone (phase 3.2). PM_CodUpdateADS adds the
waterlevel/ladder checks on top of this (those live in pmove_t/pml_t, not playerState_t).
================
*/
qboolean BG_CodCanADS( const playerState_t *ps ) {
	if ( ps->aiChar ) {
		return qfalse;
	}
	if ( !( bg_cod.enable && bg_cod.adsEnable ) ) {
		return qfalse;
	}
	if ( ps->weapon <= WP_NONE || ps->weapon >= WP_NUM_WEAPONS || !bg_codWeapons[ps->weapon].canADS ) {
		return qfalse;
	}

	switch ( ps->weaponstate ) {
	case WEAPON_RAISING:
	case WEAPON_RAISING_TORELOAD:
	case WEAPON_DROPPING:
	case WEAPON_DROPPING_TORELOAD:
	case WEAPON_RELOADING:
		return qfalse;
	default:
		break;
	}

	if ( ps->eFlags & ( EF_ZOOMING | EF_MG42_ACTIVE | EF_MELEE_ACTIVE ) ) {
		return qfalse;
	}

	// codmod: no ADS while sliding unless cod_slideAllowADS (phase 6)
	if ( ( ps->pm_flags & PMF_COD_SLIDING ) && !bg_cod.slideAllowADS ) {
		return qfalse;
	}

	// codmod: no ADS during prone transitions; crawling blocked unless cod_proneCrawlADS (6b)
	if ( bg_cod.proneEnable ) {
		if ( ps->stats[STAT_COD_STANCE] > 0 ) {
			return qfalse;
		}
		if ( ( ps->stats[STAT_COD_FLAGS] & COD_SF_PRONE_MOVING ) && !bg_cod.proneCrawlADS ) {
			return qfalse;
		}
	}

	return qtrue;
}

